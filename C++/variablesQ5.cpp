#include<iostream>
using namespace std;
int main()
{
    cout<<"\n Size of fundamental data types:\n";
    cout<<"\n The size of(char):"<<sizeof(char)<<" bytes \n";
    cout<<"\n The size of(short):"<<sizeof(short)<<" bytes \n";
    cout<<"\n The size of(int):"<<sizeof(int)<<" bytes \n";
    cout<<"\n The size of(long):"<<sizeof(long)<<" bytes \n";
    cout<<"\n The size of(long long):"<<sizeof(long long)<<" bytes \n";
    cout<<"\n The size of(float):"<<sizeof(float)<<" bytes \n";
    cout<<"\n The size of(double):"<<sizeof(double)<<" bytes \n";
    cout<<"\n The size of(long double):"<<sizeof(long double)<<" bytes \n";
    cout<<"\n The size of(bool):"<<sizeof(bool)<<" bytes \n";

return 0;

} 

